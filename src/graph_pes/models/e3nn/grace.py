class ElementIndex(torch.nn.Module):
    """Map atomic numbers to indices into the ``elements`` list."""

    def __init__(self, elements: list[str]):
        super().__init__()
        from ase.data import atomic_numbers, chemical_symbols

        if len(set(elements)) != len(elements):
            raise ValueError(f"Duplicate elements in {elements}")
        self.elements = list(elements)
        self.Z_to_idx: torch.Tensor
        self.register_buffer(
            "Z_to_idx", torch.full((MAX_Z + 1,), -1, dtype=torch.long)
        )
        for i, symbol in enumerate(elements):
            self.Z_to_idx[atomic_numbers[symbol]] = i
        self.chemical_symbols: list[str] = chemical_symbols

    def forward(self, Z: torch.Tensor) -> torch.Tensor:
        idx = self.Z_to_idx[Z]
        with torch.no_grad():
            if (idx < 0).any():
                unknown_Z = torch.unique(Z[idx < 0])
                unknown = [self.chemical_symbols[z] for z in unknown_Z]
                raise ValueError(
                    f"Unknown elements: {unknown}. "
                    f"Expected one of {self.elements}"
                )
        return idx

    def __repr__(self) -> str:
        return uniform_repr(self.__class__.__name__, elements=self.elements)


class RadialFunction(torch.nn.Module):
    r"""
    Learnable radial functions, :math:`R_{nl}(r)`, generated by a bias-free
    MLP acting on a (smoothly enveloped) radial basis. The output is tiled
    over :math:`m` so that it can be directly multiplied with spherical
    harmonics of shape ``(E, (l_max + 1)^2)``.

    Using no bias terms ensures that :math:`R_{nl}(r_\text{cut}) = 0`, so long
    as the radial basis also vanishes at the cutoff.
    """

    def __init__(
        self,
        n_basis: int,
        n_rad_max: int,
        lmax: int,
        hidden_layers: list[int],
        activation: str,
    ):
        super().__init__()
        self.n_rad_max = n_rad_max
        self.lmax = lmax
        self.mlp = MLP(
            [n_basis, *hidden_layers, n_rad_max * (lmax + 1)],
            activation=activation,
            bias=False,
        )
        tile = []
        for l in range(lmax + 1):
            tile.extend([l] * (2 * l + 1))
        self.l_tile: torch.Tensor
        self.register_buffer("l_tile", _long(tile))

    def forward(self, basis: torch.Tensor) -> torch.Tensor:
        R = self.mlp(basis).view(-1, self.n_rad_max, self.lmax + 1)
        return R.index_select(-1, self.l_tile)  # (E, n, (lmax+1)^2)


class ScalarSingleParticleBasis(torch.nn.Module):
    r"""
    The ACE atomic (single-particle) basis with a scalar chemical indicator:

    .. math::

        A_{i,nlm} = \text{Agg}_{j \in \mathcal{N}_i}
        \left[ R_{nl}(r_{ij}) \, Y_{lm}(\hat{r}_{ij}) \, (W z_j)_n \right]

    where :math:`z_j` is the chemical embedding of neighbour :math:`j`.
    """

    def __init__(self, lmax: int, aggregation: NeighbourAggregationMode):
        super().__init__()
        self.irreps_out = natural_parity_irreps(lmax)
        self.aggregation = NeighbourAggregation.parse(aggregation)

    def forward(
        self,
        radial: torch.Tensor,  # (E, n, D)
        sph_harmonics: torch.Tensor,  # (E, D)
        neighbour_chemistry: torch.Tensor,  # (E, n)
        graph: AtomicGraph,
    ) -> torch.Tensor:
        a = (
            radial
            * sph_harmonics.unsqueeze(1)
            * neighbour_chemistry.unsqueeze(-1)
        )
        return self.aggregation(a, graph)  # (N, n, D)

    def __repr__(self) -> str:
        return uniform_repr(
            self.__class__.__name__,
            irreps_out=_describe(self.irreps_out),
            aggregation=self.aggregation,
            stringify=False,
        )


class ChannelwiseProduct(torch.nn.Module):
    r"""
    A weight-free, channel-wise, Clebsch-Gordan coupled product of two
    equivariant features (``ProductFunction`` in the reference
    implementation):

    .. math::

        (x \otimes y)^{(l_1 l_2) L}_{c,M} = \sqrt{2L+1}
        \sum_{m_1 m_2} C^{L M}_{l_1 m_1 l_2 m_2} \, x^{l_1}_{c, m_1}
        \, y^{l_2}_{c, m_2}

    for every pair of irrep instances with :math:`l_1, l_2 \le l_\text{max}`
    and every :math:`L \le L_\text{max}`. Only couplings that generate
    natural-parity outputs (:math:`p_1 p_2 = (-1)^L`) are retained.

    Parameters
    ----------
    left_irreps
        Irrep instances of the left input.
    right_irreps
        Irrep instances of the right input.
    lmax
        Maximum :math:`l` of input instances to use.
    Lmax
        Maximum :math:`L` of output instances.
    symmetric
        Whether the left and right inputs are the same tensor, in which case
        symmetrically equivalent coupling paths are only generated once.
    """

    def __init__(
        self,
        left_irreps: IrrepList,
        right_irreps: IrrepList,
        lmax: int,
        Lmax: int,
        symmetric: bool = False,
    ):
        super().__init__()

        if symmetric and list(left_irreps) != list(right_irreps):
            raise ValueError("symmetric products require identical inputs")

        left_offsets = _offsets(left_irreps)
        right_offsets = _offsets(right_irreps)

        irreps_out: list[o3.Irrep] = []
        left_idx: list[int] = []
        right_idx: list[int] = []
        out_idx: list[int] = []
        cg: list[float] = []

        current = 0
        for i, ir1 in enumerate(left_irreps):
            if ir1.l > lmax:
                continue
            for j, ir2 in enumerate(right_irreps):
                if ir2.l > lmax or (symmetric and j > i):
                    continue
                parity = ir1.p * ir2.p
                for L in range(
                    abs(ir1.l - ir2.l), min(ir1.l + ir2.l, Lmax) + 1
                ):
                    if parity != (-1) ** L:
                        continue
                    C = o3.wigner_3j(ir1.l, ir2.l, L, dtype=torch.float64)
                    C = C * math.sqrt(2 * L + 1)
                    for m1, m2, M in torch.nonzero(C.abs() > 1e-10).tolist():
                        left_idx.append(left_offsets[i] + m1)
                        right_idx.append(right_offsets[j] + m2)
                        out_idx.append(current + M)
                        cg.append(C[m1, m2, M].item())
                    irreps_out.append(o3.Irrep(L, parity))
                    current += 2 * L + 1

        if not irreps_out:
            raise ValueError(
                "No valid coupling paths found between "
                f"{_describe(left_irreps)} and {_describe(right_irreps)} "
                f"for lmax={lmax}, Lmax={Lmax}"
            )

        self.irreps_in = (list(left_irreps), list(right_irreps))
        self.irreps_out = irreps_out
        self.dim_out = current
        self.right_dim = _dim(right_irreps)

        self.left_idx: torch.Tensor
        self.right_idx: torch.Tensor
        self.out_idx: torch.Tensor
        self.flat_idx: torch.Tensor
        self.cg: torch.Tensor
        self.register_buffer("left_idx", _long(left_idx))
        self.register_buffer("right_idx", _long(right_idx))
        self.register_buffer("out_idx", _long(out_idx))
        self.register_buffer(
            "flat_idx",
            _long(
                [l * self.right_dim + r for l, r in zip(left_idx, right_idx)]
            ),
        )
        self.register_buffer("cg", _float(cg))

    def forward(self, x: torch.Tensor, y: torch.Tensor) -> torch.Tensor:
        # x: (N, C, D_left), y: (N, C, D_right) -> (N, C, D_out)
        prod = (
            x.index_select(-1, self.left_idx)
            * y.index_select(-1, self.right_idx)
            * self.cg
        )
        out = torch.zeros(
            (prod.shape[0], prod.shape[1], self.dim_out),
            dtype=prod.dtype,
            device=prod.device,
        )
        return out.index_add(-1, self.out_idx, prod)

    def couple_outer(self, outer: torch.Tensor) -> torch.Tensor:
        """
        Couple a (pre-computed and flattened) outer product of the left and
        right inputs, of shape ``(N, C, D_left * D_right)``.
        """
        prod = outer.index_select(-1, self.flat_idx) * self.cg
        out = torch.zeros(
            (prod.shape[0], prod.shape[1], self.dim_out),
            dtype=prod.dtype,
            device=prod.device,
        )
        return out.index_add(-1, self.out_idx, prod)

    def __repr__(self) -> str:
        left, right = self.irreps_in
        return uniform_repr(
            self.__class__.__name__,
            f"({_describe(left)}) x ({_describe(right)}) "
            f"-> {_describe(self.irreps_out)}",
            paths=len(self.irreps_out),
            stringify=False,
        )


class ChannelMixer(torch.nn.Module):
    r"""
    Equivariant channel mixing (``FCRight2Left`` in the reference
    implementation). Each irrep instance, :math:`k`, of the left input is
    linearly mixed over channels, and all instances of the right input that
    share the same irrep are (separately) linearly mixed and added on:

    .. math::

        x^\prime_k = \frac{1}{\sqrt{1 + |\mathcal{M}_k|}} \left(
        W_k \, x_k + \sum_{q \in \mathcal{M}_k} V_{kq} \, y_q \right)

    where :math:`\mathcal{M}_k` is the set of right-instances with the same
    irrep as :math:`x_k`. The output has the same irrep instances as the left
    input.
    """

    def __init__(
        self,
        left_irreps: IrrepList,
        left_channels: int,
        right_irreps: IrrepList,
        right_channels: int,
        out_channels: int,
    ):
        super().__init__()
        self.irreps_out = list(left_irreps)
        self.channels = (left_channels, right_channels, out_channels)

        left_offsets = _offsets(left_irreps)
        right_offsets = _offsets(right_irreps)

        collect_to: list[int] = []
        collect_from: list[int] = []
        right_tile: list[int] = []
        norms: list[float] = []
        n_pairs = 0
        for i, ir_l in enumerate(left_irreps):
            matches = [j for j, ir_r in enumerate(right_irreps) if ir_r == ir_l]
            for j in matches:
                for m in range(ir_l.dim):
                    collect_to.append(left_offsets[i] + m)
                    collect_from.append(right_offsets[j] + m)
                    right_tile.append(n_pairs)
                n_pairs += 1
            norms.extend([1 / math.sqrt(1 + len(matches))] * ir_l.dim)

        self.w_left = torch.nn.Parameter(
            torch.randn(len(left_irreps), out_channels, left_channels)
        )
        self.w_right = torch.nn.Parameter(
            torch.randn(n_pairs, out_channels, right_channels)
        )
        self.left_norm: Final[float] = 1 / math.sqrt(left_channels)
        self.right_norm: Final[float] = 1 / math.sqrt(right_channels)

        self.left_tile: torch.Tensor
        self.right_tile: torch.Tensor
        self.collect_to: torch.Tensor
        self.collect_from: torch.Tensor
        self.out_norm: torch.Tensor
        self.register_buffer(
            "left_tile", _long(_instance_of_each_component(left_irreps))
        )
        self.register_buffer("right_tile", _long(right_tile))
        self.register_buffer("collect_to", _long(collect_to))
        self.register_buffer("collect_from", _long(collect_from))
        self.register_buffer("out_norm", _float(norms))

    def forward(self, left: torch.Tensor, right: torch.Tensor) -> torch.Tensor:
        w_left = self.w_left.index_select(0, self.left_tile)  # (D, K, C)
        out = torch.einsum("dkc,ncd->nkd", w_left, left) * self.left_norm

        w_right = self.w_right.index_select(0, self.right_tile)  # (D', K, C')
        r = right.index_select(-1, self.collect_from)
        r = torch.einsum("dkc,ncd->nkd", w_right, r) * self.right_norm
        out = out.index_add(-1, self.collect_to, r)

        return out * self.out_norm

    def __repr__(self) -> str:
        left_c, right_c, out_c = self.channels
        return uniform_repr(
            self.__class__.__name__,
            f"{_describe(self.irreps_out)}",
            channels=f"({left_c}, {right_c}) -> {out_c}",
            stringify=False,
        )


class _ReduceInput(torch.nn.Module):
    def __init__(
        self,
        input_index: int,
        irreps: IrrepList,
        channels: int,
        lmax: int,
        out_irreps: list[o3.Irrep],
        out_channels: int,
        n_elements: int | None,
    ):
        super().__init__()
        self.input_index: Final[int] = input_index

        offsets = _offsets(irreps)
        out_offsets = _offsets(out_irreps)

        selected: list[int] = []
        tile: list[int] = []
        target: list[int] = []
        target_irrep: list[int] = []
        n_instances = 0
        for i, ir in enumerate(irreps):
            if ir.l > lmax or ir not in out_irreps:
                continue
            k = out_irreps.index(ir)
            for m in range(ir.dim):
                selected.append(offsets[i] + m)
                tile.append(n_instances)
                target.append(out_offsets[k] + m)
                target_irrep.append(k)
            n_instances += 1

        self.n_instances = n_instances
        self.channels = channels
        self.target_irrep = target_irrep

        shape = (n_instances, out_channels, channels)
        if n_elements is not None:
            shape = (n_elements, *shape)
        self.weights = torch.nn.Parameter(torch.randn(shape))
        self.element_dependent: Final[bool] = n_elements is not None

        self.selected: torch.Tensor
        self.tile: torch.Tensor
        self.target: torch.Tensor
        self.norm: torch.Tensor
        self.register_buffer("selected", _long(selected))
        self.register_buffer("tile", _long(tile))
        self.register_buffer("target", _long(target))
        # placeholder: filled in by FunctionReduce once fan-ins are known
        self.register_buffer("norm", torch.ones(len(selected)))

    def forward(
        self, x: torch.Tensor, element_idx: torch.Tensor
    ) -> torch.Tensor:
        x = x.index_select(-1, self.selected)  # (N, C, D)
        if self.element_dependent:
            w = self.weights[element_idx]  # (N, I, K, C)
            w = w.index_select(1, self.tile)  # (N, D, K, C)
            out = torch.einsum("ndkc,ncd->nkd", w, x)
        else:
            w = self.weights.index_select(0, self.tile)  # (D, K, C)
            out = torch.einsum("dkc,ncd->nkd", w, x)
        return out * self.norm


class FunctionReduce(torch.nn.Module):
    r"""
    Linearly reduce a collection of equivariant features onto a set of
    output irreps (``FunctionReduceN`` in the reference implementation):

    .. math::

        y^{L}_{k} = \sum_{\alpha} \sum_{q \in \alpha, \, l_q = L}
        \sum_c W^{\alpha}_{q, k c}(\mu_i) \, x^{\alpha}_{q, c}

    where :math:`\alpha` runs over the inputs, :math:`q` over the irrep
    instances of each input, and :math:`c` over channels. If
    ``element_dependent`` is ``True``, the weights depend on the chemical
    element, :math:`\mu_i`, of the central atom.

    Parameters
    ----------
    inputs
        A list of ``(irreps, channels, lmax)`` tuples describing each input.
        Only instances with :math:`l \le` ``lmax`` are used.
    out_irreps
        The (unique) irreps to reduce onto.
    out_channels
        The number of output channels.
    n_elements
        If not ``None``, use element-dependent weights for this many elements.
    """

    def __init__(
        self,
        inputs: list[tuple[IrrepList, int, int]],
        out_irreps: list[o3.Irrep],
        out_channels: int,
        n_elements: int | None = None,
    ):
        super().__init__()

        # only keep output irreps that some input can actually contribute to
        out_irreps = [
            ir
            for ir in out_irreps
            if any(ir in irreps and ir.l <= lmax for irreps, _, lmax in inputs)
        ]
        if not out_irreps:
            raise ValueError("No inputs contribute to the requested outputs")
        self.irreps_out = out_irreps
        self.out_channels = out_channels
        self.dim_out = _dim(out_irreps)

        reducers = [
            _ReduceInput(
                i, irreps, channels, lmax, out_irreps, out_channels, n_elements
            )
            for i, (irreps, channels, lmax) in enumerate(inputs)
        ]
        reducers = [r for r in reducers if r.n_instances > 0]

        # normalise each output irrep by the square-root of its total fan-in
        fan_in = [0] * len(out_irreps)
        for r in reducers:
            # map each selected instance to the output irrep it targets
            instance_target: dict[int, int] = {}
            for t, k in zip(r.tile.tolist(), r.target_irrep):
                instance_target[t] = k
            for k in instance_target.values():
                fan_in[k] += r.channels
        for r in reducers:
            r.norm = _float([1 / math.sqrt(fan_in[k]) for k in r.target_irrep])

        self.reducers = UniformModuleList(reducers)
        self.element_dependent = n_elements is not None

    def forward(
        self, features: list[torch.Tensor], element_idx: torch.Tensor
    ) -> torch.Tensor:
        N = element_idx.shape[0]
        out = torch.zeros(
            (N, self.out_channels, self.dim_out),
            dtype=features[0].dtype,
            device=features[0].device,
        )
        for reducer in self.reducers:
            x = features[reducer.input_index]
            out = out.index_add(-1, reducer.target, reducer(x, element_idx))
        return out

    def __repr__(self) -> str:
        return uniform_repr(
            self.__class__.__name__,
            f"{len(self.reducers)} inputs -> "
            f"{self.out_channels}x({_describe(self.irreps_out)})",
            element_dependent=self.element_dependent,
            stringify=False,
        )


class EquivariantSingleParticleBasis(torch.nn.Module):
    r"""
    The semi-local atomic basis of the second GRACE layer
    (``SingleParticleBasisFunctionEquivariantInd`` in the reference
    implementation). Equivariant indicator features of neighbour :math:`j`
    are coupled with the bond's radial and angular basis:

    .. math::

        A^{(2)}_{i, n L M} = \text{Agg}_{j \in \mathcal{N}_i} \left[
        \left( R_{nl}(r_{ij}) Y_{l}(\hat{r}_{ij}) \otimes I_{j,n}^{l'}
        \right)^{L}_M \right]

    For efficiency, the (linear) Clebsch-Gordan coupling is performed after
    aggregation over neighbours.
    """

    def __init__(
        self,
        lmax_sph: int,
        indicator_irreps: IrrepList,
        Lmax: int,
        aggregation: NeighbourAggregationMode,
    ):
        super().__init__()
        self.coupling = ChannelwiseProduct(
            natural_parity_irreps(lmax_sph),
            indicator_irreps,
            lmax=max(lmax_sph, max(ir.l for ir in indicator_irreps)),
            Lmax=Lmax,
        )
        self.irreps_out = self.coupling.irreps_out
        self.aggregation = NeighbourAggregation.parse(aggregation)

    def forward(
        self,
        radial: torch.Tensor,  # (E, n, D_Y)
        sph_harmonics: torch.Tensor,  # (E, D_Y)
        indicator: torch.Tensor,  # (N, n, D_I)
        graph: AtomicGraph,
    ) -> torch.Tensor:
        ry = radial * sph_harmonics.unsqueeze(1)  # (E, n, D_Y)
        neighbour_indicator = index_over_neighbours(indicator, graph)
        outer = ry.unsqueeze(-1) * neighbour_indicator.unsqueeze(-2)
        # (explicit sizes so that graphs with no edges also work)
        outer = outer.reshape(
            outer.shape[0], outer.shape[1], outer.shape[2] * outer.shape[3]
        )
        aggregated = self.aggregation(outer, graph)  # (N, n, D_Y * D_I)
        return self.coupling.couple_outer(aggregated)

    def __repr__(self) -> str:
        return uniform_repr(
            self.__class__.__name__,
            self.coupling,
            aggregation=self.aggregation,
            stringify=False,
        )


class ProductBasis(torch.nn.Module):
    r"""
    Generate the many-body product basis of a single GRACE layer from an
    atomic basis, :math:`A`:

    .. math::

        \begin{align*}
        A^{(1)} &= \text{Mix}(A, A) \\
        AA &= A^{(1)} \otimes A^{(1)} \\
        AAA &= \text{Mix}(AA, A) \otimes A^{(1)} \\
        AAAA &= \text{Mix}(AA, A) \otimes \text{Mix}(AA, A)
        \end{align*}

    where each :math:`\text{Mix}` has independent weights (see
    :class:`ChannelMixer`) and :math:`\otimes` is a
    :class:`ChannelwiseProduct`. Products up to ``max_order`` atomic basis
    functions are generated.
    """

    def __init__(
        self,
        base_irreps: IrrepList,
        base_channels: int,
        lmax: int,
        max_order: int,
        product_channels: int,
        Lmax_3: int = 0,
        Lmax_4: int = 0,
    ):
        super().__init__()
        if not 1 <= max_order <= 4:
            raise ValueError(f"max_order must be in [1, 4], got {max_order}")
        self.max_order: Final[int] = max_order

        base_irreps = list(base_irreps)
        self.irreps_out: list[list[o3.Irrep]] = [base_irreps]
        self.channels_out: list[int] = [base_channels]

        self.mix_1: ChannelMixer | None = None
        self.prod_2: ChannelwiseProduct | None = None
        self.mix_2: ChannelMixer | None = None
        self.prod_3: ChannelwiseProduct | None = None
        self.mix_3: ChannelMixer | None = None
        self.prod_4: ChannelwiseProduct | None = None

        if max_order >= 2:
            self.mix_1 = ChannelMixer(
                base_irreps,
                base_channels,
                base_irreps,
                base_channels,
                product_channels,
            )
            self.prod_2 = ChannelwiseProduct(
                base_irreps, base_irreps, lmax, lmax, symmetric=True
            )
            AA = self.prod_2.irreps_out
            self.irreps_out.append(AA)
            self.channels_out.append(product_channels)

            if max_order >= 3:
                self.mix_2 = ChannelMixer(
                    AA,
                    product_channels,
                    base_irreps,
                    base_channels,
                    product_channels,
                )
                self.prod_3 = ChannelwiseProduct(AA, base_irreps, lmax, Lmax_3)
                self.irreps_out.append(self.prod_3.irreps_out)
                self.channels_out.append(product_channels)

            if max_order >= 4:
                self.mix_3 = ChannelMixer(
                    AA,
                    product_channels,
                    base_irreps,
                    base_channels,
                    product_channels,
                )
                self.prod_4 = ChannelwiseProduct(
                    AA, AA, lmax, Lmax_4, symmetric=True
                )
                self.irreps_out.append(self.prod_4.irreps_out)
                self.channels_out.append(product_channels)

    def forward(self, A: torch.Tensor) -> list[torch.Tensor]:
        features = [A]
        if self.mix_1 is not None and self.prod_2 is not None:
            A1 = self.mix_1(A, A)
            AA = self.prod_2(A1, A1)
            features.append(AA)

            if self.mix_2 is not None and self.prod_3 is not None:
                AA1 = self.mix_2(AA, A)
                features.append(self.prod_3(AA1, A1))

            if self.mix_3 is not None and self.prod_4 is not None:
                AA2 = self.mix_3(AA, A)
                features.append(self.prod_4(AA2, AA2))

        return features

    def describe(self) -> list[tuple[list[o3.Irrep], int]]:
        return list(zip(self.irreps_out, self.channels_out))


class GRACESecondLayer(torch.nn.Module):
    """
    The second (semi-local) layer of a GRACE-2L model: builds equivariant
    indicators from the first layer's features, passes these along bonds to
    create a new atomic basis, and generates its product basis.
    """

    def __init__(
        self,
        first_layer: ProductBasis,
        n_basis: int,
        n_elements: int,
        embedding_size: int,
        lmax_1: int,
        lmax_2: int,
        n_rad_max: int,
        product_channels: int,
        max_order: int,
        indicator_lmax: int,
        indicator_channels: int,
        radial_hidden_layers: list[int],
        radial_activation: str,
        aggregation: NeighbourAggregationMode,
    ):
        super().__init__()

        indicator_irreps = natural_parity_irreps(indicator_lmax)
        first = first_layer.describe()
        # all but the 4-body product contribute equivariant indicators
        indicator_inputs = [
            (irreps, channels, indicator_lmax if i < 3 else 0)
            for i, (irreps, channels) in enumerate(first)
        ]
        self.indicator_reduce = FunctionReduce(
            indicator_inputs,
            indicator_irreps,
            indicator_channels,
            n_elements=n_elements,
        )
        self.indicator_expand = FunctionReduce(
            [
                (
                    self.indicator_reduce.irreps_out,
                    indicator_channels,
                    indicator_lmax,
                )
            ],
            indicator_irreps,
            n_rad_max,
        )

        self.radial = RadialFunction(
            n_basis,
            n_rad_max,
            lmax_1,
            radial_hidden_layers,
            radial_activation,
        )
        self.chemistry = torch.nn.Linear(embedding_size, n_rad_max, bias=False)
        self.B0 = ScalarSingleParticleBasis(lmax_1, aggregation)
        self.YI = EquivariantSingleParticleBasis(
            lmax_1,
            self.indicator_expand.irreps_out,
            lmax_2,
            aggregation,
        )
        self.B = FunctionReduce(
            [
                (self.YI.irreps_out, n_rad_max, lmax_2),
                (self.B0.irreps_out, n_rad_max, lmax_2),
            ],
            natural_parity_irreps(lmax_2),
            n_rad_max,
        )
        self.products = ProductBasis(
            self.B.irreps_out,
            n_rad_max,
            lmax_2,
            max_order,
            product_channels,
        )

    def forward(
        self,
        first_layer_features: list[torch.Tensor],
        radial_basis: torch.Tensor,
        sph_harmonics: torch.Tensor,
        embeddings: torch.Tensor,
        element_idx: torch.Tensor,
        neighbour_element_idx: torch.Tensor,
        graph: AtomicGraph,
    ) -> list[torch.Tensor]:
        indicator = self.indicator_reduce(first_layer_features, element_idx)
        indicator = self.indicator_expand([indicator], element_idx)

        R = self.radial(radial_basis)
        chemistry = self.chemistry(embeddings)[neighbour_element_idx]
        B0 = self.B0(R, sph_harmonics, chemistry, graph)
        YI = self.YI(R, sph_harmonics, indicator, graph)
        B = self.B([YI, B0], element_idx)
        return self.products(B)


