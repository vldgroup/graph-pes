def _per_layer(value: int | list[int], layers: int, name: str) -> list[int]:
    if isinstance(value, int):
        return [value] * layers
    value = list(value)
    if len(value) != layers:
        raise ValueError(
            f"Expected {layers} values for {name}, got {len(value)}: {value}"
        )
    return value


class GRACE(GraphPESModel):
    r"""
    The `Graph Atomic Cluster Expansion (GRACE)
    <https://doi.org/10.1103/PhysRevX.14.021036>`__ architecture, following
    the ``GRACE_1LAYER`` and ``GRACE_2LAYER`` models of the reference
    `tensorpotential <https://github.com/ICAMS/grace-tensorpotential>`__
    implementation.

    **Single layer (GRACE-1L).** Bond lengths are expanded in a radial basis
    and mapped by a bias-free MLP onto radial functions,
    :math:`R_{nl}(r)`. Together with spherical harmonics, :math:`Y_{lm}`,
    and a learnable chemical embedding of each neighbour, :math:`z_j`, these
    form the ACE atomic basis (see :class:`ScalarSingleParticleBasis`):

    .. math::

        A_{i,nlm} = \frac{1}{\langle N \rangle}\sum_{j \in \mathcal{N}_i}
        R_{nl}(r_{ij}) \, Y_{lm}(\hat{r}_{ij}) \, (W z_j)_n

    Higher body-order features, :math:`AA`, :math:`AAA` and :math:`AAAA`, are
    generated from channel-wise Clebsch-Gordan products of (linearly mixed)
    atomic basis functions (see :class:`ProductBasis`). All invariant
    features are linearly reduced, with weights that depend on the element
    of the central atom, onto ``n_mlp_dens + 1`` "densities",
    :math:`\rho_i`, and the local energy is

    .. math::

        \varepsilon_i = \rho_{i,0} + \text{MLP}(\rho_{i,1:})

    **Two layers (GRACE-2L).** The first layer's (up to ``indicator_lmax``)
    equivariant features are reduced onto per-atom indicators,
    :math:`I_j`, which are coupled with :math:`R_{nl}(r_{ij})
    Y_{lm}(\hat{r}_{ij})` along each bond to form a semi-local atomic basis
    (see :class:`EquivariantSingleParticleBasis`). A second product basis is
    generated from this, and invariants from both layers enter the readout.
    The receptive field of a GRACE-2L model is hence twice the ``cutoff``.

    Please cite the following if you use this model in your research:

    .. code-block:: bibtex

        @article{Bochkarev2024GRACE,
            title = {
                Graph Atomic Cluster Expansion for Semilocal Interactions
                beyond Equivariant Message Passing
            },
            author = {
                Bochkarev, Anton and Lysogorskiy, Yury and Drautz, Ralf
            },
            journal = {Physical Review X},
            volume = {14},
            pages = {021036},
            year = {2024},
            doi = {10.1103/PhysRevX.14.021036},
        }

    Parameters
    ----------
    elements
        The chemical elements this model can handle.
    cutoff
        The radial cutoff (in Å).
    layers
        The number of GRACE layers: ``1`` (local, GRACE-1L) or ``2``
        (semi-local, GRACE-2L).
    lmax
        The maximum angular momentum of the atomic basis (and product basis)
        functions. Pass a list of two values to set this per layer for
        ``layers=2``.
    n_rad_max
        The number of radial channels, :math:`n`, of the atomic basis. Pass a
        list of two values to set this per layer for ``layers=2``.
    prod_func_n_max
        The number of channels used for the product basis. Defaults to
        ``n_rad_max``. Pass a list to set this per layer.
    max_order
        The maximum number of atomic basis functions in a product (i.e. the
        body order minus one), in :math:`[1, 4]`.
    n_mlp_dens
        The number of invariant "densities" passed to the readout MLP.
    readout_width
        The width of the hidden layer of the readout MLP.
    embedding_size
        The size of the learnable chemical embedding.
    n_rad_base
        The number of radial basis functions.
    radial_expansion
        The radial basis to use. Defaults to
        :class:`~graph_pes.models.components.distances.Chebyshev`. See
        :class:`~graph_pes.models.components.distances.DistanceExpansion` for
        other options.
    envelope_order
        The order, :math:`p`, of the
        :class:`~graph_pes.models.components.distances.PolynomialEnvelope`
        applied to the radial basis.
    radial_hidden_layers
        The hidden layer widths of the radial function MLPs.
    radial_activation
        The activation function of the radial function MLPs.
    readout_activation
        The activation function of the readout MLP.
    indicator_lmax
        (``layers=2`` only) The maximum angular momentum of the indicators
        passed between layers.
    indicator_channels
        (``layers=2`` only) The number of channels in the element-dependent
        reduction that generates the indicators.
    neighbour_aggregation
        How to aggregate over neighbours when forming atomic bases. The
        default, ``"constant_fixed"``, divides by the average number of
        neighbours in the training set. See
        :class:`~graph_pes.models.components.aggregation.NeighbourAggregation`.

    Examples
    --------
    A GRACE-1L model similar to the "small" ``GRACE_1LAYER`` preset:

    .. code-block:: python

        >>> from graph_pes.models import GRACE
        >>> model = GRACE(elements=["H", "C", "N", "O"], cutoff=6.0)

    A GRACE-2L model for use with ``graph-pes-train``:

    .. code-block:: yaml

        model:
            +GRACE:
                elements: [H, C, N, O]
                cutoff: 5.0
                layers: 2
                lmax: [3, 2]
                n_rad_max: [20, 32]
                max_order: 3
                n_mlp_dens: 8
    """

    def __init__(
        self,
        elements: list[str],
        cutoff: float = DEFAULT_CUTOFF,
        layers: int = 1,
        lmax: int | list[int] = 3,
        n_rad_max: int | list[int] = 20,
        prod_func_n_max: int | list[int] | None = None,
        max_order: int = 3,
        n_mlp_dens: int = 10,
        readout_width: int = 64,
        embedding_size: int = 128,
        n_rad_base: int = 8,
        radial_expansion: type[DistanceExpansion] | str = "Chebyshev",
        envelope_order: int = 5,
        radial_hidden_layers: list[int] | None = None,
        radial_activation: str = "Tanh",
        readout_activation: str = "SiLU",
        indicator_lmax: int = 1,
        indicator_channels: int = 16,
        neighbour_aggregation: NeighbourAggregationMode = "constant_fixed",
    ):
        super().__init__(
            cutoff=cutoff,
            implemented_properties=["local_energies"],
        )

        if layers not in (1, 2):
            raise ValueError(f"GRACE supports 1 or 2 layers, got {layers}")
        if not elements:
            raise ValueError("GRACE requires a non-empty list of elements")

        lmaxs = _per_layer(lmax, layers, "lmax")
        n_rads = _per_layer(n_rad_max, layers, "n_rad_max")
        prod_channels = (
            n_rads
            if prod_func_n_max is None
            else _per_layer(prod_func_n_max, layers, "prod_func_n_max")
        )
        if radial_hidden_layers is None:
            radial_hidden_layers = [64, 64]
        if layers == 2 and indicator_lmax > lmaxs[0]:
            raise ValueError(
                f"indicator_lmax ({indicator_lmax}) cannot exceed the first "
                f"layer's lmax ({lmaxs[0]})"
            )

        self.elements = list(elements)
        self.n_layers = layers
        n_elements = len(elements)

        # radial and angular things
        expansion = get_distance_expansion(radial_expansion)
        self.radial_basis = expansion(
            n_features=n_rad_base, cutoff=cutoff, trainable=True
        )
        self.envelope = PolynomialEnvelope(cutoff=cutoff, p=envelope_order)
        self.spherical_harmonics = SphericalHarmonics(
            o3.Irreps.spherical_harmonics(lmaxs[0]),
            normalize=True,
            normalization="component",
        )

        # chemistry
        self.element_index = ElementIndex(elements)
        self.embeddings = torch.nn.Parameter(
            torch.randn(n_elements, embedding_size)
        )

        # first layer
        self.radial = RadialFunction(
            n_rad_base,
            n_rads[0],
            lmaxs[0],
            radial_hidden_layers,
            radial_activation,
        )
        self.chemistry = torch.nn.Linear(embedding_size, n_rads[0], bias=False)
        self.A = ScalarSingleParticleBasis(lmaxs[0], neighbour_aggregation)
        self.products = ProductBasis(
            self.A.irreps_out,
            n_rads[0],
            lmaxs[0],
            max_order,
            prod_channels[0],
            Lmax_3=indicator_lmax if layers == 2 else 0,
        )
        readout_inputs = self.products.describe()

        # second layer
        self.second_layer: GRACESecondLayer | None = None
        if layers == 2:
            self.second_layer = GRACESecondLayer(
                first_layer=self.products,
                n_basis=n_rad_base,
                n_elements=n_elements,
                embedding_size=embedding_size,
                lmax_1=lmaxs[0],
                lmax_2=lmaxs[1],
                n_rad_max=n_rads[1],
                product_channels=prod_channels[1],
                max_order=max_order,
                indicator_lmax=indicator_lmax,
                indicator_channels=indicator_channels,
                radial_hidden_layers=radial_hidden_layers,
                radial_activation=radial_activation,
                aggregation=neighbour_aggregation,
            )
            readout_inputs += self.second_layer.products.describe()

        # readout
        self.densities = FunctionReduce(
            [(irreps, channels, 0) for irreps, channels in readout_inputs],
            [o3.Irrep("0e")],
            n_mlp_dens + 1,
            n_elements=n_elements,
        )
        self.readout = MLP(
            [n_mlp_dens, readout_width, 1],
            activation=readout_activation,
            bias=False,
        )
        self.scaler = LocalEnergiesScaler()

    def forward(self, graph: AtomicGraph) -> dict[PropertyKey, torch.Tensor]:
        element_idx = self.element_index(graph.Z)
        neighbour_element_idx = element_idx[graph.neighbour_list[1]]

        distances = neighbour_distances(graph)
        radial_basis = self.radial_basis(distances.view(-1, 1))
        radial_basis = radial_basis * self.envelope(distances).view(-1, 1)
        sph_harmonics = self.spherical_harmonics(neighbour_vectors(graph))

        # first layer
        R = self.radial(radial_basis)
        chemistry = self.chemistry(self.embeddings)[neighbour_element_idx]
        A = self.A(R, sph_harmonics, chemistry, graph)
        features = self.products(A)

        # second layer
        if self.second_layer is not None:
            features = features + self.second_layer(
                features,
                radial_basis,
                sph_harmonics,
                self.embeddings,
                element_idx,
                neighbour_element_idx,
                graph,
            )

        # readout
        rho = self.densities(features, element_idx)[:, :, 0]  # (N, K)
        local_energies = rho[:, 0] + self.readout(rho[:, 1:]).squeeze(-1)

        return {"local_energies": self.scaler(local_energies, graph)}
