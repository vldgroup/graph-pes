def _offsets(irreps: IrrepList) -> list[int]:
    """Start index of each irrep instance in a flattened feature vector."""
    offsets, current = [], 0
    for ir in irreps:
        offsets.append(current)
        current += ir.dim
    return offsets


def _dim(irreps: IrrepList) -> int:
    return sum(ir.dim for ir in irreps)


def _instance_of_each_component(irreps: IrrepList) -> list[int]:
    """Map each component of a flattened feature to its irrep instance."""
    out = []
    for i, ir in enumerate(irreps):
        out.extend([i] * ir.dim)
    return out


def _describe(irreps: IrrepList) -> str:
    """Compact string description, e.g. ``3x0e+2x1o+2e``."""
    counts: dict[o3.Irrep, int] = {}
    for ir in irreps:
        counts[ir] = counts.get(ir, 0) + 1
    parts = []
    for ir in sorted(counts, key=lambda ir: (ir.l, -ir.p)):
        n = counts[ir]
        parts.append(f"{n}x{ir}" if n > 1 else str(ir))
    return "+".join(parts)


def natural_parity_irreps(lmax: int) -> list[o3.Irrep]:
    r"""The irreps :math:`l^{(-1)^l}` for :math:`l \le l_\text{max}`."""
    return [o3.Irrep(l, (-1) ** l) for l in range(lmax + 1)]


def _long(x: list[int]) -> torch.Tensor:
    return torch.tensor(x, dtype=torch.long)


def _float(x: list[float]) -> torch.Tensor:
    return torch.tensor(x, dtype=torch.get_default_dtype())


