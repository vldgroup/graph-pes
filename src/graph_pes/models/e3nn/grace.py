r"""
An implementation of the Graph Atomic Cluster Expansion (GRACE) family of
models.

GRACE builds on the Atomic Cluster Expansion (ACE): atomic environments are
first projected onto a single-particle (atomic) basis, :math:`A`, and
many-body features are then generated by taking (Clebsch-Gordan coupled)
products of these atomic basis functions. The multi-layer variant
("GRACE-2L") passes equivariant "indicator" features from the first layer
along each bond to construct a second, semi-local, atomic basis.

Internally, all equivariant features are stored as tensors of shape
``(N, channels, D)``, where ``D`` is the total dimension of an (ordered)
list of :class:`e3nn.o3.Irrep` *instances*. Unlike :class:`e3nn.o3.Irreps`,
this list may contain the same irrep many times: e.g. the product of two
atomic bases contains several ``0e`` instances, one for each of the
``(l1, l2)`` coupling paths that generate a scalar.
"""

